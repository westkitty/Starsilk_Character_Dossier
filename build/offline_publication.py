#!/usr/bin/env python3
"""Generate the narrow, versioned Phase 11 offline museum shell.

The service worker owns only a repository-relative scope.  It precaches a
small reading shell and public JSON indexes; published media remains strictly
on demand and is never written to Cache Storage by this worker.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

import jinja2

ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = ROOT / "docs"
SOURCE_DIR = ROOT / "src" / "offline"
TEMPLATES_DIR = ROOT / "src" / "templates"
CONFIG_FILE = SOURCE_DIR / "config.json"
AUTHORITY_FILE = SOURCE_DIR / "AUTHORITY.md"
OUTPUT_NAMES = {
    "manifest.webmanifest",
    "service-worker.js",
    "offline-client.js",
    "offline.html",
    "offline.css",
    "offline-icon.svg",
}
MEDIA_PREFIX = "/assets/media/"
CACHE_PREFIX = "starsilk-offline-shell-"


def text(path: Path) -> str:
    return path.read_text(encoding="utf-8").rstrip() + "\n"


def json_text(value: object) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def load_config() -> dict:
    config = json.loads(CONFIG_FILE.read_text(encoding="utf-8"))
    required = {"schema", "name", "short_name", "description", "theme_color", "background_color", "media_policy", "precache"}
    if set(config) != required or config["schema"] != "starsilk-offline-museum/1":
        raise RuntimeError("offline config schema is unsupported")
    if config["media_policy"] != "on-demand-never-service-worker-cached":
        raise RuntimeError("offline media policy must remain on-demand and never service-worker-cached")
    precache = config["precache"]
    if not isinstance(precache, list) or not precache or len(precache) != len(set(precache)):
        raise RuntimeError("offline precache must be a non-empty unique list")
    if any(not isinstance(item, str) or item.startswith("/") or ".." in Path(item).parts for item in precache):
        raise RuntimeError("offline precache paths must be repository-relative")
    if any("assets/media" in item for item in precache):
        raise RuntimeError("published media must never be precached")
    return config


def source_output(path: str) -> str:
    sources = {
        "offline-client.js": TEMPLATES_DIR / "offline-client.js",
        "offline.css": TEMPLATES_DIR / "offline.css",
        "offline-icon.svg": TEMPLATES_DIR / "offline-icon.svg",
    }
    return text(sources[path])


def cache_fingerprint(config: dict, outputs: dict[str, str]) -> str:
    digest = hashlib.sha256()
    digest.update(CONFIG_FILE.read_bytes())
    digest.update(AUTHORITY_FILE.read_bytes())
    for relative in config["precache"]:
        digest.update(relative.encode("utf-8"))
        payload = outputs.get(relative)
        if payload is None:
            target = DOCS_DIR / ("index.html" if relative == "." else relative)
            if not target.is_file():
                raise RuntimeError(f"offline precache target is missing: docs/{relative}")
            payload = target.read_text(encoding="utf-8")
        digest.update(payload.encode("utf-8"))
    return digest.hexdigest()[:16]


def service_worker(config: dict, cache_name: str) -> str:
    precache = json.dumps(config["precache"], indent=2)
    return f"""/* Generated by build/offline_publication.py.  Do not hand-edit. */
const CACHE_NAME = {cache_name!r};
const CACHE_PREFIX = {CACHE_PREFIX!r};
const PRECACHE = {precache};
const OFFLINE_FALLBACK = 'offline.html';
const MEDIA_PATH = {MEDIA_PREFIX!r};
let installFailures = [];

function isSameOrigin(request) {{ return new URL(request.url).origin === self.location.origin; }}
function isPublishedMedia(request) {{ return new URL(request.url).pathname.includes(MEDIA_PATH); }}
function isScopeRoot(request) {{ return new URL(request.url).pathname === new URL(self.registration.scope).pathname; }}
function message(type) {{ return {{source: 'starsilk-offline', type: type}}; }}
async function notify(type) {{
  const clients = await self.clients.matchAll({{type: 'window', includeUncontrolled: true}});
  clients.forEach((client) => client.postMessage(message(type)));
}}
async function clearOwnedCaches() {{
  const names = await caches.keys();
  await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX)).map((name) => caches.delete(name)));
}}

self.addEventListener('install', (event) => {{
  event.waitUntil((async () => {{
    const cache = await caches.open(CACHE_NAME);
    installFailures = [];
    for (const path of PRECACHE) {{
      try {{ await cache.add(path); }} catch (error) {{ installFailures.push(path); }}
    }}
    await self.skipWaiting();
  }})());
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil((async () => {{
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map((name) => caches.delete(name)));
    await self.clients.claim();
    await notify(installFailures.length ? 'offline-degraded' : 'offline-ready');
  }})());
}});

self.addEventListener('message', (event) => {{
  if(!event.data || event.data.type !== 'CLEAR_STARSILK_OFFLINE_CACHE') return;
  event.waitUntil(clearOwnedCaches().then(() => notify('offline-cache-cleared')).catch(() => notify('offline-cache-clear-failed')));
}});

self.addEventListener('fetch', (event) => {{
  const request = event.request;
  if(request.method !== 'GET' || !isSameOrigin(request) || isPublishedMedia(request)) return;
  if(request.mode === 'navigate') {{
    event.respondWith(fetch(request).catch(async () => (await caches.match(request)) || (isScopeRoot(request) && await caches.match('index.html')) || (await caches.match(OFFLINE_FALLBACK))));
    return;
  }}
  const pathname = new URL(request.url).pathname;
  if(PRECACHE.some((path) => pathname.endsWith('/' + path) || pathname.endsWith(path))) {{
    event.respondWith(caches.match(request).then((cached) => cached || fetch(request)));
  }}
}});
"""


def render_outputs() -> dict[str, str]:
    config = load_config()
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(str(TEMPLATES_DIR)), autoescape=True)
    outputs = {
        "offline-client.js": source_output("offline-client.js"),
        "offline.css": source_output("offline.css"),
        "offline-icon.svg": source_output("offline-icon.svg"),
        "offline.html": env.get_template("offline.html.j2").render(config=config).rstrip() + "\n",
        "manifest.webmanifest": json_text({
            "id": "./",
            "name": config["name"],
            "short_name": config["short_name"],
            "description": config["description"],
            "start_url": "./",
            "scope": "./",
            "display": "standalone",
            "theme_color": config["theme_color"],
            "background_color": config["background_color"],
            "icons": [{"src": "offline-icon.svg", "sizes": "192x192", "type": "image/svg+xml", "purpose": "any maskable"}],
        }),
    }
    fingerprint = cache_fingerprint(config, outputs)
    outputs["service-worker.js"] = service_worker(config, CACHE_PREFIX + fingerprint)
    return outputs


def check_outputs(outputs: dict[str, str]) -> list[str]:
    errors = []
    actual = {path.name for path in DOCS_DIR.iterdir() if path.is_file() and path.name in OUTPUT_NAMES}
    if actual != OUTPUT_NAMES:
        errors.append("generated offline file set differs from expected output")
    for relative, expected in outputs.items():
        path = DOCS_DIR / relative
        if not path.exists():
            errors.append(f"generated offline output differs: docs/{relative}")
            continue
        try:
            current = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            errors.append(f"unreadable generated offline output docs/{relative}: {exc}")
            continue
        if current != expected:
            errors.append(f"generated offline output differs: docs/{relative}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true")
    args, unknown = parser.parse_known_args()
    if unknown: print(f"ERROR: unknown argument(s): {' '.join(unknown)}", file=sys.stderr); return 2
    try: outputs = render_outputs()
    except (OSError, json.JSONDecodeError, RuntimeError, jinja2.TemplateError) as exc:
        print(f"ERROR: offline publication generation failed: {exc}", file=sys.stderr); return 1
    if args.check:
        errors = check_outputs(outputs)
        if errors: print("\n".join(f"ERROR: {error}" for error in errors), file=sys.stderr); return 1
        print(f"OK: {len(outputs)} offline museum outputs match generator output."); return 0
    for stale in OUTPUT_NAMES:
        path = DOCS_DIR / stale
        if path.exists() and path.is_file(): path.unlink()
    for relative, content in outputs.items():
        path = DOCS_DIR / relative; path.write_text(content, encoding="utf-8"); print(f"Wrote {path.relative_to(ROOT)} ({len(content):,} bytes)")
    return 0


if __name__ == "__main__": raise SystemExit(main())
